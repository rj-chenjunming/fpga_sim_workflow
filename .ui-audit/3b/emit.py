#!/usr/bin/env python3
"""3B-5 emit the paste-ready tokens.css block + the generated markdown tables.

Reads .ui-audit/3b/mapping.json (written by build_mapping.py) and writes only
under .ui-audit/3b/:
  tokens-proposed.css
  _gen-absorption.md   (per-token absorption rows, for absorption.md)
  _gen-over12.md       (every ΔRGB>12 literal, for gaps.md)
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
M = json.load(open(os.path.join(HERE, "mapping.json"), encoding="utf-8"))

SECTIONS = [
    ("底（浅表面）", ["--panel", "--surface", "--surface-2", "--bg"]),
    ("线（分隔/边框）", ["--line", "--line-strong", "--line-soft"]),
    ("字（正文/说明）", ["--text", "--text-2", "--text-3", "--muted", "--faint"]),
    ("主色（青绿）", ["--primary", "--primary-hover", "--primary-weak", "--primary-line"]),
    ("成功", ["--ok", "--ok-weak", "--ok-line"]),
    ("警告", ["--warn", "--warn-weak", "--warn-line", "--warn-line-soft", "--warn-ink"]),
    ("危险", ["--danger", "--danger-weak", "--danger-line"]),
    ("紫（次要标签）", ["--purple", "--purple-weak"]),
    ("侧栏（深墨）", ["--rail", "--rail-hover", "--rail-border", "--rail-text",
                 "--rail-muted", "--rail-accent"]),
    ("浮层 / 阴影 / 白色叠加", ["--overlay", "--rail-tint", "--rail-line",
                          "--shadow-tint", "--shadow-pop"]),
]
S52 = {  # §5.2 suggested value, for the deviation column
    "--panel": "#fff", "--surface": "#f8faf9", "--surface-2": "#fcfdfb", "--bg": "#f4f6f5",
    "--line": "#e1e8e4", "--line-strong": "#c7d4cc", "--line-soft": "#eef1f5",
    "--text": "#213831", "--text-2": "#3d5545", "--muted": "#61746c", "--faint": "#5f6f67",
    "--primary": "现状", "--primary-hover": "现状", "--primary-weak": "现状",
    "--primary-line": "现状", "--ok": "#24734d", "--ok-weak": "#edf7ef", "--ok-line": "#bfe8d8",
    "--warn": "#9a5e16", "--warn-weak": "#fff6e8", "--warn-line": "#f3d19e",
    "--warn-line-soft": "#ead7b7", "--warn-ink": "#7a6234", "--danger": "#b34140",
    "--danger-weak": "#fff0ef", "--danger-line": "#f5c6c6", "--purple": "#7357a0",
    "--purple-weak": "#f3eef9", "--rail": "现状", "--rail-hover": "现状",
    "--rail-active": "#304b3d", "--rail-border": "#3a5a4a", "--rail-text": "现状",
    "--rail-muted": "现状", "--rail-accent": "#b9d5aa", "--overlay": "#12251ab3",
    "--mono-bg": "#20382b", "--mono-text": "#dde8dc", "--surface-3": "#f6f9f4",
    "--danger-line-soft": "#ebc4bf", "--purple-line": "#e1d8ec",
}


def rgb_of(hexs):
    h = hexs.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def drgb(a, b):
    return max(abs(a[0] - b[0]), abs(a[1] - b[1]), abs(a[2] - b[2]))


def emit_css():
    tok = {t["name"]: t for t in M["tokens"]}
    lines = [
        "/* FPGA Flow · shared visual tokens; all assets stay local.",
        "   3B 配色令牌化提案（2026-10-30）：颜色令牌 40 个 = 既有 24 + 新增 16；",
        "   非颜色令牌 --shadow/--radius/--ease-out/--font-* 原样保留。",
        "   依据 doc/agents/开工提示词_UI批次3C与3B.md §5.2；吸收表见 .ui-audit/3b/absorption.md。",
        "   说明：既有 24 个颜色令牌的值一律未动；16 个新增令牌的值取所吸收存量族的中位色。 */",
        ":root{",
        "  color-scheme:light;",
    ]
    for title, names in SECTIONS:
        parts = []
        for n in names:
            parts.append("%s:%s" % (n, tok[n]["fitted"]))
        lines.append("  /* %s */" % title)
        lines.append("  " + ";".join(parts) + ";")
    lines += [
        "  /* 非颜色令牌（原样） */",
        "  --shadow:0 2px 4px #20372b03,0 8px 24px #20372b03;",
        "  --radius:12px;",
        "  --ease-out:cubic-bezier(0.22,1,0.36,1);",
        '  --font-sans:-apple-system,BlinkMacSystemFont,"Segoe UI","Noto Sans SC","Microsoft YaHei",sans-serif;',
        '  --font-mono:"SFMono-Regular",Consolas,"Liberation Mono",monospace;',
        "}",
        "",
    ]
    with open(os.path.join(HERE, "tokens-proposed.css"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return tok


def emit_absorption(tok):
    by_tok = collections.defaultdict(list)
    for r in M["rows"]:
        by_tok[r["token"]].append(r)
    out = ["<!-- generated by .ui-audit/3b/emit.py; do not hand-edit -->", ""]
    out.append("| 组 | 令牌 | §5.2 建议值 | 采用值（本提案） | 与建议值 ΔRGB | 吸收的字面量（归一化，次数） | 吸收条数 | 组内最大 ΔRGB |")
    out.append("|---|---|---|---|---|---|---|---|")
    for title, names in SECTIONS:
        for n in names:
            t = tok[n]
            rows = by_tok.get(n, [])
            agg = collections.Counter((r["current"], r["alpha"]) for r in rows)
            items = []
            for (lit, a), cnt in sorted(agg.items(), key=lambda kv: -kv[1]):
                items.append("%s%s×%d" % (lit, "(α%d)" % a if a != 255 else "", cnt))
            sug = S52.get(n, "—")
            dev = "—" if sug in ("现状", "—") else str(drgb(rgb_of(t["fitted"]), rgb_of(sug)))
            mx = max((r["delta"] for r in rows), default=0)
            out.append("| %s | `%s` | %s | %s | %s | %s | %d | %d |" % (
                title, n, sug, t["fitted"], dev, " ".join(items) or "（无吸收）",
                len(rows), mx))
    out.append("")
    out.append("合计：吸收字面量出现 %d 次（%d 个不同值）；组内最大 ΔRGB 见上表。" % (
        len(M["rows"]), len({(r["current"], r["alpha"]) for r in M["rows"]})))
    with open(os.path.join(HERE, "_gen-absorption.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")


def emit_over12():
    ALPHA = {"--rail-tint", "--rail-line", "--shadow-tint", "--shadow-pop", "--overlay"}
    out = ["<!-- generated by .ui-audit/3b/emit.py; do not hand-edit -->", ""]
    out.append("| 字面量 | 归一化值 | 落点令牌 | ΔRGB | α（现值→令牌） | 出现 | 位置（文件:行 属性 选择器） |")
    out.append("|---|---|---|---|---|---|---|")
    rows = [r for r in M["rows"] if r["delta"] > 12]
    order = sorted(rows, key=lambda r: (-r["delta"], r["file"], r["line"]))
    for r in order:
        out.append("| `%s` | %s | `%s` | %d | %s | %d | %s:%d %s %s |" % (
            r["current"], r["current"] if r["current"].startswith("rgb") else r["current"],
            r["token"], r["delta"],
            ("%d→%d" % (r["alpha"], r["token_alpha"])) if r["token"] in ALPHA else "—",
            1, r["file"], r["line"], r["property"], r["selector"]))
    out.append("")
    out.append("ΔRGB>12 共 **%d** 条出现 / **%d** 个不同值（归一化 rgb+alpha）。" % (
        len(rows), len({(r["current"], r["alpha"]) for r in rows})))
    with open(os.path.join(HERE, "_gen-over12.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    return len(rows), len({(r["current"], r["alpha"]) for r in rows})


tok = emit_css()
emit_absorption(tok)
n, d = emit_over12()
print("tokens-proposed.css written:", len(SECTIONS), "sections,",
      sum(len(n) for _, n in SECTIONS), "colour tokens")
print("over12 rows:", n, "distinct:", d)
