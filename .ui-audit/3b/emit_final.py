#!/usr/bin/env python3
"""3B-final emitter: turns final-design.json into the five hand-off artefacts.

Writes only .ui-audit/3b/:
  tokens-final.css          paste-ready :root{}
  map-final.tsv             file/line/property/current/token/ΔRGB
  map-values-final.tsv      literal/alpha/token/ΔRGB/occurrences  (survives 3C)
  absorption-final.md       per-token absorption table + counts
  gaps-final.md             residual exceptions (alpha / inline / mockup)
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, "final-design.json"), encoding="utf-8"))
TOK = {t["name"]: t for t in D["tokens"]}
ROWS = D["rows"]

FAM_TITLE = {"neutral": "底 / 线 / 字 / 侧栏（neutral 共享）",
             "primary": "主色（青绿）", "ok": "成功", "warn": "警告",
             "danger": "危险", "purple": "紫（次要标签）",
             "blue": "数据/元信息蓝", "av": "头像身份色（.a1–.a6）",
             "alpha": "浮层 / 阴影 / 白色叠加（alpha）"}
FAM_ORDER = ["neutral", "primary", "ok", "warn", "danger", "purple", "blue", "av", "alpha"]
ORDER_HINT = {"--panel": 0, "--surface": 1, "--surface-2": 2, "--surface-3": 3,
              "--bg": 4, "--line": 10, "--line-strong": 11, "--line-soft": 12,
              "--line-warm": 13, "--line-tint": 14, "--text": 20, "--text-2": 21,
              "--text-3": 22, "--text-4": 23, "--text-5": 24, "--muted": 25,
              "--faint": 26, "--rail": 30, "--rail-hover": 31, "--rail-active": 32,
              "--rail-border": 33, "--rail-text": 34, "--rail-muted": 35,
              "--rail-muted-2": 36, "--rail-accent": 37, "--rail-deep": 38}
ALPHA = {"--overlay", "--rail-tint", "--rail-line", "--rail-line-strong",
         "--shadow-tint", "--shadow-raise", "--shadow-pop"}


def rgb_of(h):
    h = h.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def drgb(a, b):
    return max(abs(a[0] - b[0]), abs(a[1] - b[1]), abs(a[2] - b[2]))


def emit_css():
    present = list(TOK)
    missing = []
    lines = [
        "/* FPGA Flow · shared visual tokens; all assets stay local.",
        "   3B 配色令牌化 · 收口版（裁决 A：令牌上限放到 46–50+，保 ΔRGB<=12）。",
        "   组成 = 既有 24 个颜色令牌（值未动）+ 新增语义/alpha/头像令牌；",
        "   非颜色令牌 --shadow/--radius/--ease-out/--font-* 原样保留。",
        "   吸收表与判据：.ui-audit/3b/absorption-final.md；残余例外：gaps-final.md。 */",
        ":root{",
        "  color-scheme:light;",
    ]
    for fam in FAM_ORDER:
        names = [n for n, v in TOK.items() if v["family"] == fam]
        names.sort(key=lambda n: (ORDER_HINT.get(n, 90), n))
        if not names:
            continue
        lines.append("  /* %s */" % FAM_TITLE.get(fam, fam))
        for n in names:
            lines.append("  %s:%s;" % (n, TOK[n]["value"]))
    lines += [
        "  /* 非颜色令牌（原样） */",
        "  --shadow:0 2px 4px #20372b03,0 8px 24px #20372b03;",
        "  --radius:12px;",
        "  --ease-out:cubic-bezier(0.22,1,0.36,1);",
        '  --font-sans:-apple-system,BlinkMacSystemFont,"Segoe UI","Noto Sans SC","Microsoft YaHei",sans-serif;',
        '  --font-mono:"SFMono-Regular",Consolas,"Liberation Mono",monospace;',
        "}",
        "",
    ]
    open(os.path.join(HERE, "tokens-final.css"), "w", encoding="utf-8").write("\n".join(lines))
    return present + missing


def emit_maps():
    with open(os.path.join(HERE, "map-final.tsv"), "w", encoding="utf-8") as fh:
        fh.write("file\tline\tproperty\tcurrent\ttoken\tdelta\n")
        for r in ROWS:
            fh.write("%s\t%d\t%s\t%s\t%s\t%d\n" % (r["file"], r["line"], r["property"],
                                                   r["current"], r["token"], r["delta"]))
    agg = collections.OrderedDict()
    for r in ROWS:
        k = (r["current"], r["alpha"])
        e = agg.setdefault(k, {"token": r["token"], "delta": r["delta"], "n": 0})
        e["n"] += 1
    with open(os.path.join(HERE, "map-values-final.tsv"), "w", encoding="utf-8") as fh:
        fh.write("literal\talpha\ttoken\tdelta\toccurrences\n")
        for (lit, al), e in agg.items():
            fh.write("%s\t%d\t%s\t%d\t%d\n" % (lit, al, e["token"], e["delta"], e["n"]))
    return agg


def emit_absorption(names):
    by = collections.defaultdict(list)
    for r in ROWS:
        by[r["token"]].append(r)
    out = ["<!-- generated by .ui-audit/3b/emit_final.py; do not hand-edit -->", "",
           "| 组 | 令牌 | 值 | 吸收的字面量（归一化，次数） | 吸收条数 | 组内最大 ΔRGB | 判据 |",
           "|---|---|---|---|---|---|---|"]
    for fam in FAM_ORDER:
        for n in sorted([x for x, v in TOK.items() if v["family"] == fam],
                        key=lambda x: (ORDER_HINT.get(x, 90), x)):
            if n not in TOK:
                continue
            title = FAM_TITLE.get(fam, fam)
            rows = by.get(n, [])
            items = collections.Counter((r["current"], r["alpha"]) for r in rows)
            txt = " ".join("%s%s×%d" % (lit, "(α%d)" % a if a != 255 else "", c)
                           for (lit, a), c in sorted(items.items(), key=lambda kv: -kv[1]))
            mx = max((r["delta"] for r in rows if r["alpha"] == 255), default=0)
            crit = "alpha 合成" if n in ALPHA else "ΔRGB≤12"
            out.append("| %s | `%s` | %s | %s | %d | %d | %s |" % (
                title, n, TOK[n]["value"], txt or "（无吸收）", len(rows), mx, crit))
    out += ["", "颜色令牌合计 **%d**；吸收色值出现 **%d** 次 / **%d** 个不同值。" %
            (len(TOK), len(ROWS), len({(r["current"], r["alpha"]) for r in ROWS}))]
    open(os.path.join(HERE, "_gen-absorption-final.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    names = emit_css()
    emit_maps()
    emit_absorption(names)
    print("tokens:", len(names), "| rows:", len(ROWS))
