"""受控验证 G1 的等待与签署后信号；不替代真实闸门验收。"""

from types import SimpleNamespace

import pytest

from workflows.chunks import gates, host_steps


class Data:
    def __init__(self):
        self.state = {}
        self.pauses = []
        self.signals = []
        self.is_resume = False
        self.resume = None

    def get_state(self, key):
        return self.state.get(key)

    async def async_set_state(self, key, value):
        self.state[key] = value

    async def async_pause_for(self, **kwargs):
        self.pauses.append(kwargs)

    async def async_emit(self, name, value):
        self.signals.append((name, value))


@pytest.mark.asyncio
async def test_g1_waits_then_emits_only_after_authority_check(tmp_path, monkeypatch):
    events = []
    ctx = SimpleNamespace(run_dir=tmp_path, run_id="RUN-1", mode="drill", kb=None,
                          event=lambda kind, **kw: events.append((kind, kw)),
                          node_started=lambda node: events.append(("start", node)),
                          node_finished=lambda node, **kw: events.append(("finish", node)),
                          node_failed=lambda node, **kw: events.append(("failed", node)))
    monkeypatch.setattr(gates, "ctx_of", lambda data: ctx)
    monkeypatch.setattr(gates, "_cycles_view", lambda *a: {"g2_rework_cycles": 0, "n6_n8_cycles": 0})
    monkeypatch.setattr(gates, "_persist_cycles", lambda *a: None)
    monkeypatch.setattr(gates, "_state_facts", lambda data: {})
    monkeypatch.setattr(gates, "_ledger_notes", lambda ctx: [])
    monkeypatch.setattr(gates, "_counts_for", lambda data: {})
    monkeypatch.setattr(gates, "_cycle", lambda *a: 0)
    monkeypatch.setattr(gates.contracts, "gate_material", lambda **kw: {"hard_block": [], "difference_items": {}})
    monkeypatch.setattr(gates.contracts, "report_claimed_verdict", lambda *a: None)
    monkeypatch.setattr(gates, "decision_options", lambda *a, **kw: [])
    data = Data()
    assert (await gates.gate1(data))["status"] == "waiting"
    assert data.pauses[0]["interrupt_id"] == "G1_diff_confirm:0"
    assert data.signals == []

    monkeypatch.setattr(gates, "precheck_decision", lambda **kw: {"entries": {}})
    monkeypatch.setattr(gates, "authority_record", lambda *a: {"signed_at": "t"})
    monkeypatch.setattr(gates, "human_signed_flag", lambda *a: True)
    monkeypatch.setattr(gates, "append_decision_ledger", lambda *a: None)
    monkeypatch.setattr(host_steps, "run_kb_tool", lambda *a, **kw: {"rc": 0})
    data.is_resume = True
    data.resume = SimpleNamespace(value={"decision": "confirmed", "actor": "human:test", "reason": "checked"})
    result = await gates.gate1(data)
    assert result["branch"] == "G1_CONFIRMED"
    assert data.signals[0][0] == "G1_CONFIRMED"

@pytest.mark.asyncio
@pytest.mark.parametrize("phase", ["enter", "resume"])
async def test_no_impact_guard_rejects_before_gate_side_effects(phase):
    data = Data()
    data.state["n5_impact"] = {"must_change_count": 1}
    ctx = SimpleNamespace()
    call = gates._enter if phase == "enter" else gates._resumed
    with pytest.raises(gates.GatePreconditionFailed):
        await call(ctx, data, "G1_no_impact")
    assert data.pauses == []
    assert data.signals == []
    assert data.state == {"n5_impact": {"must_change_count": 1}}


@pytest.mark.asyncio
async def test_n9_full_regression_selects_index_targets_before_slot(tmp_path, monkeypatch):
    from workflows.chunks import long_jobs

    selected = [{"case": "tc_a", "sandbox_path": str(tmp_path / "tc_a.sv"), "md5": "a"}]
    calls = []
    ctx = SimpleNamespace(run_dir=tmp_path, mode="real", runner=object(),
                          node_started=lambda node: None)
    data = Data()
    data.state["gate_decisions"] = {"G1_no_impact": {"decision": "full_regression"}}
    monkeypatch.setattr(long_jobs, "ctx_of", lambda _: ctx)
    monkeypatch.setattr(long_jobs, "_baseline_full_targets", lambda: selected)
    monkeypatch.setattr(long_jobs, "_target_cases", lambda _: pytest.fail("sandbox branch used"))
    monkeypatch.setattr(long_jobs, "_verify_targets", lambda cases: calls.append(cases))
    monkeypatch.setattr(long_jobs, "_slot_job_id", lambda _: "job")

    async def deny_slot(*args, **kwargs):
        return {"retry": True}

    monkeypatch.setattr(long_jobs, "_acquire_slot", deny_slot)
    assert await long_jobs.n9_submit(data) == {"status": "slot_retry"}
    assert calls == [selected]
